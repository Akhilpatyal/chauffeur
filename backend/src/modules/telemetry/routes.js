import { z } from 'zod';
import { validate, docSchema } from '../../lib/validate.js';
import { recordPageView } from '../../services/visitors.js';

/*
 * The one public endpoint the frontend calls to say "somebody looked at this
 * page".
 *
 * WHY A BEACON AND NOT SERVER-SIDE COUNTING
 *
 * The site is served as a static bundle from a CDN with client-side routing,
 * so most page views never reach this API at all — the server sees one request
 * for the app and then nothing as the visitor moves between pages. Counting
 * server-side would report one page view per visit and miss the entire browse,
 * which is the part that says which destination page is doing the work.
 *
 * WHY IT IS SAFE TO HAVE OPEN
 *
 * It accepts nothing that can be read back out. The session id is hashed
 * before storage, the payload is a path and a few labels with hard length
 * caps, and there is no response body to probe. The worst a determined abuser
 * achieves is inflating a traffic chart, which the rate limit bounds and the
 * bot flag makes visible.
 */
const pageViewBody = z.object({
  /* Generated by the browser for this visit and held in sessionStorage, so it
   * dies with the tab. Hashed on arrival — the raw value is never stored. */
  sessionId: z.string().trim().min(8).max(100),
  path: z.string().trim().min(1).max(300),
  referrer: z.string().trim().max(500).optional(),
  utm: z
    .object({
      source: z.string().trim().max(80).optional(),
      medium: z.string().trim().max(80).optional(),
      campaign: z.string().trim().max(120).optional(),
    })
    .optional(),
  /* Reported when they leave a page, so the previous view can be completed.
   * Capped at an hour: a tab left open overnight is not an hour of reading,
   * and an uncapped figure would wreck every average on the dashboard. */
  dwellMs: z.coerce.number().int().min(0).max(60 * 60 * 1000).optional(),
});

export default async function telemetryRoutes(fastify) {
  fastify.post(
    '/telemetry/page-view',
    {
      /*
       * Generous but bounded. A real visit sends one of these per page, so a
       * browse of thirty pages in ten minutes is normal and must not be
       * throttled; sixty in a minute is not a person reading.
       */
      config: {
        rateLimit: {
          max: 60,
          timeWindow: '1 minute',
          keyGenerator: (request) => `telemetry:${request.ipHash ?? request.ip}`,
        },
      },
      preValidation: validate({ body: pageViewBody }),
      schema: {
        tags: ['public'],
        summary: 'Record a page view',
        description:
          'Anonymous. The session id is hashed before storage and expires with the browser ' +
          'tab; no cookie is set and no IP address is kept, only the same keyed hash used ' +
          'elsewhere in the API.',
        body: docSchema(pageViewBody, 'PageView'),
        response: { 202: { description: 'Accepted', type: 'object' } },
      },
    },
    async (request, reply) => {
      /*
       * 202 and an empty body, returned without waiting for the write.
       *
       * The visitor is mid-navigation; making them wait on our analytics write
       * would be measuring the page speed by slowing it down. A dropped beacon
       * costs one row in a traffic chart, which is why this is the one place
       * in the API where a failed write is simply let go.
       */
      recordPageView({
        sessionId: request.body.sessionId,
        path: request.body.path,
        referrer: request.body.referrer,
        utm: request.body.utm ?? {},
        dwellMs: request.body.dwellMs,
        userAgent: request.headers['user-agent'],
        ipHash: request.ipHash,
        /* Set by Cloudflare and most CDNs. Absent in development, which is
         * why it is optional rather than derived from the address. */
        country: request.headers['cf-ipcountry'],
      }).catch((error) => {
        request.log.debug({ err: error }, 'could not record page view');
      });

      return reply.status(202).send({ data: { accepted: true } });
    },
  );
}
