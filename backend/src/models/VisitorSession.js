import mongoose from 'mongoose';

const { Schema } = mongoose;

/*
 * Who is on the site, and what happened to them.
 *
 * This exists to answer one commercial question the lead table cannot: of the
 * people who looked at the Spiti page, how many asked us anything? A lead
 * table shows the numerator and has no idea about the denominator, so a page
 * that gets heavy traffic and converts nobody looks identical to a page
 * nobody visits.
 *
 * WHAT IS DELIBERATELY NOT STORED
 *
 * No IP address, no cookie that survives the visit, no cross-site identifier,
 * no fingerprint of the device. The session id is generated by the browser
 * for that visit and kept in sessionStorage, so it dies with the tab; the IP
 * is reduced to the same keyed hash used everywhere else, only so that
 * "same visitor" and "obvious bot" are answerable. Nothing here identifies a
 * person, which keeps the useful analytics on the right side of what a
 * traveller would expect us to be doing with their visit.
 */
const pageViewSchema = new Schema(
  {
    path: { type: String, required: true, maxlength: 300 },
    at: { type: Date, required: true },
    /* Milliseconds on the page, reported when they leave it. Null while they
     * are still there, which is also how the exit page is identified. */
    dwellMs: { type: Number, default: null },
  },
  { _id: false },
);

const visitorSessionSchema = new Schema(
  {
    sessionId: { type: String, required: true, unique: true },

    startedAt: { type: Date, required: true },
    lastSeenAt: { type: Date, required: true, index: true },

    /* Where they arrived and where they went. The landing page is the one
     * worth optimising; the exit page is the one worth investigating. */
    landingPath: { type: String, maxlength: 300 },
    exitPath: { type: String, maxlength: 300 },
    /* Capped by the recording service. A long browse is interesting; an
     * unbounded array is a document that eventually cannot be saved. */
    pageViews: { type: [pageViewSchema], default: [] },
    pageViewCount: { type: Number, default: 0 },

    /* Hostname only, never the full referring URL — the path of the page that
     * linked to us can itself carry someone's search terms. */
    referrerHost: { type: String, default: null, maxlength: 120 },
    utm: {
      source: { type: String, default: null, maxlength: 80 },
      medium: { type: String, default: null, maxlength: 80 },
      campaign: { type: String, default: null, maxlength: 120 },
    },

    /* Coarse on purpose: 'mobile' | 'tablet' | 'desktop' and a browser family.
     * Enough to notice the booking form is broken on mobile Safari, not
     * enough to re-identify anybody. */
    device: { type: String, default: null },
    browser: { type: String, default: null },
    country: { type: String, default: null, maxlength: 2 },

    ipHash: { type: String, default: null, index: true },

    /*
     * The point of the whole collection: did this visit turn into an enquiry.
     * Set by the lead intake when the submission carries a session id.
     *
     * The flag and the link are separate fields on purpose. When somebody
     * exercises their right to erasure the link has to go — it is a thread
     * from a customer record back to that person's browsing — but the fact
     * that a visit to the Spiti page produced an enquiry is a statistic about
     * a page, not about a person. Keeping them as one field would force a
     * choice between honouring the erasure and keeping the conversion rate
     * honest, so every aggregation reads `converted` and only the drill-down
     * reads `convertedLead`.
     */
    converted: { type: Boolean, default: false, index: true },
    convertedLead: { type: Schema.Types.ObjectId, ref: 'Lead', default: null },
    convertedAt: { type: Date, default: null },

    /* Sessions that never got past one page in under two seconds are almost
     * all crawlers. Flagged rather than dropped, so the dashboard can show
     * human traffic by default and still prove the filter is honest. */
    isBot: { type: Boolean, default: false, index: true },
  },
  { timestamps: false, versionKey: false },
);

visitorSessionSchema.index({ startedAt: -1 });
visitorSessionSchema.index({ landingPath: 1, startedAt: -1 });
visitorSessionSchema.index({ convertedAt: -1 });
visitorSessionSchema.index({ isBot: 1, startedAt: -1 });

/* Sixty days: enough to compare a campaign against the month before it. */
visitorSessionSchema.index({ startedAt: 1 }, { expireAfterSeconds: 60 * 24 * 60 * 60 });

export const VisitorSession =
  mongoose.models.VisitorSession ?? mongoose.model('VisitorSession', visitorSessionSchema);
export default VisitorSession;
